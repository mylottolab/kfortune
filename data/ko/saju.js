/* 평생 사주 글 엮기 */
window.KF_SAJU_COMPOSE = function (p, c, sj, d, fill, esc) {
  var nm = { name: esc(p.name) }, F = function (s) { return fill(s, nm); };
  var il = (sj.ilju || [])[c.pillars.day.i] || { t: d.me[c.dayMaster].name, p: [] };
  var dm = sj.dm[c.dayMaster];
  var free = [F(dm[0])].concat(il.p.slice(0, 1).map(F));
  c.missing.forEach(function (e) { free.push(F(sj.elNone[e])); });
  // 가장 많은 십신(비견 제외 우선)
  var t = c.tens.slice(), top = 0; for (var i = 0; i < 10; i++) if (t[i] > t[top] || (t[i] === t[top] && top === 0 && i > 0)) top = i;
  var tt = sj.ten[top];
  var many = c.elements.indexOf(Math.max.apply(null, c.elements));
  var weak = c.missing.length ? c.missing[0] : c.elements.indexOf(Math.min.apply(null, c.elements));
  var str = c.strength >= 56 ? 'strong' : c.strength <= 44 ? 'weak' : 'balanced';
  var now = new Date().getFullYear() - c.solar.y, cur = c.daeun.list[0];
  c.daeun.list.forEach(function (x) { if (now >= x.age) cur = x; });
  var paid = [
    { h: sj.h.nature }, F(dm[1]), F(dm[2]), F(tt.p)].concat(il.p.slice(1).map(F)).concat([
    { h: sj.h.balance }, F(c.elements[many] >= 3 ? sj.elMany[many] : ''), F(sj.strength[str]),
    { h: sj.h.money }, F(tt.money), { h: sj.h.love }, F(tt.love), { h: sj.h.work }, F(tt.work),
    { h: sj.h.health }, F(sj.health[weak]) + ' ' + F(sj.healthNote),
    { h: sj.h.daeun + ' · ' + cur.pillar.txt + ' (' + cur.age + '~)' }, F(sj.daeun[cur.tenS])]).filter(function (x) { return x; });
  return { title: il.t, free: free, paid: paid, lockedTitles: sj.locked };
};
